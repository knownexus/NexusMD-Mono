// Writes installer/apps.generated.nsh: the list of apps the Windows installer offers, taken from the
// apps' manifests, so adding an app means adding a module and nothing here.
//
//   node installer/gen-apps-nsh.mjs
//
// NSIS has no arrays, so the list is a macro that calls another macro once per app; installer.nsh
// uses it to build the checklist, to copy the ticked apps and to name their shortcuts.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repo = resolve(here, '..', '..', '..')
export const generatedPath = join(here, 'apps.generated.nsh')

export function readApps(modulesDir = join(repo, 'modules')) {
  return readdirSync(modulesDir)
    .filter(id => existsSync(join(modulesDir, id, 'app.manifest.json')))
    .map(id => JSON.parse(readFileSync(join(modulesDir, id, 'app.manifest.json'), 'utf8')))
    .sort((a, b) => (a.order ?? 0) - (b.order ?? 0) || a.id.localeCompare(b.id))
}

// A string inside an NSIS "quoted" argument: $ starts a variable, and a quote ends the string.
const quote = s => `"${String(s).replace(/\$/g, '$$$$').replace(/"/g, '$\\"')}"`

export function appsNsh(apps, appsDir) {
  const lines = [
    '; Generated by installer/gen-apps-nsh.mjs from the apps\' manifests. Do not edit.',
    `!define NEXUS_APPS_DIR ${quote(appsDir)}`,
    `!define NEXUS_APP_COUNT ${apps.length}`,
    '',
    '; Calls <macro> once per app: <index> <id> <label> <productName>',
    '!macro NexusForEachApp macro',
    ...apps.map((a, i) => `  !insertmacro \${macro} ${i} ${quote(a.id)} ${quote(a.label)} ${quote(a.productName)}`),
    '!macroend',
    '',
  ]
  return lines.join('\n')
}

export function writeAppsNsh({ appsDir = join(repo, 'dist', 'desktop', 'split', 'apps'), out = generatedPath } = {}) {
  const apps = readApps()
  if (!apps.length) throw new Error('No apps found under modules/')
  writeFileSync(out, appsNsh(apps, appsDir))
  return apps
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const apps = writeAppsNsh()
  console.log(`Wrote ${generatedPath} (${apps.length} apps)`)
}
